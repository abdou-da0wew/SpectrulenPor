#ifndef SPECTRULENPOR_AS7265X_REGISTERS_H
#define SPECTRULENPOR_AS7265X_REGISTERS_H

/* AS7265x physical mailbox and virtual registers, from the AMS register map. */
#define AS7265X_STATUS 0x00U
#define AS7265X_WRITE 0x01U
#define AS7265X_READ 0x02U
#define AS7265X_TX_VALID 0x02U
#define AS7265X_RX_VALID 0x01U
#define AS7265X_VIRTUAL_WRITE_FLAG 0x80U
#define AS7265X_CONFIG 0x04U
#define AS7265X_INTEGRATION 0x05U
#define AS7265X_RAW_A 0x08U
#define AS7265X_RAW_W 0x12U
#define AS7265X_DEVICE_SELECT 0x4FU
#define AS7265X_SLAVES_PRESENT 0x30U
#define AS7265X_DEVICE_NIR 0x00U
#define AS7265X_DEVICE_SHORTWAVE 0x02U
#define AS7265X_GAIN_64X 0x30U
#define AS7265X_ALL_CHANNELS_CONTINUOUS 0x08U
#define AS7265X_DATA_READY 0x02U

#endif
